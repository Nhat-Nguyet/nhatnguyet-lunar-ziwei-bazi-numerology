"use client";
import { useState } from "react";
import { castZiWei } from "@nhatnguyet/ziwei";

export default function ZiWeiForm() {
  const [svg, setSvg] = useState("");
  const [error, setError] = useState("");

  function draw(event) {
    event.preventDefault();
    const f = new FormData(event.currentTarget);
    try {
      const chart = castZiWei({ date: f.get("date"), time: f.get("time"), gender: f.get("gender") });
      const dark = matchMedia("(prefers-color-scheme: dark)").matches;
      setSvg(chart.toSvg({ theme: dark ? "dark" : "light" }));
      setError("");
    } catch (e) {
      setSvg("");
      setError(String(e?.message ?? e));
    }
  }

  return (
    <section>
      <h2>Zi Wei Dou Shu chart</h2>
      <form onSubmit={draw}>
        <label>Birth date <input name="date" type="date" defaultValue="1990-09-19" required /></label>
        <label>Time <input name="time" type="time" defaultValue="20:00" required /></label>
        <label>
          Gender
          <select name="gender" defaultValue="male">
            <option value="male">male</option>
            <option value="female">female</option>
          </select>
        </label>
        <button>Draw</button>
      </form>
      {error && <p className="error">{error}</p>}
      {/* The SVG is generated by the library from the form values, not from HTML input. */}
      <div className="chart" dangerouslySetInnerHTML={{ __html: svg }} />
    </section>
  );
}
