// Regenerates Code.gs: the lunar library bundled by esbuild into one global
// (NhatNguyetLunar), followed by the custom functions of src/functions.js.
// Apps Script cannot import npm packages, so the whole library goes in the file.
//   node build.mjs           write Code.gs
//   node build.mjs --check   exit 1 if Code.gs is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { build } from "esbuild";

const here = new URL(".", import.meta.url);
const pkg = JSON.parse(readFileSync(new URL("node_modules/@nhatnguyet/lunar/package.json", here), "utf8"));
const out = await build({
  entryPoints: [new URL("src/library.js", here).pathname],
  bundle: true,
  format: "iife",
  globalName: "NhatNguyetLunar",
  target: "es2019",
  minify: true,
  legalComments: "none",
  write: false,
});
const code = [
  `// Nhat Nguyet lunar calendar for Google Sheets: LUNARDATE, SEXAGENARY, SOLARTERM, SOLARDATE.`,
  `// Library: @nhatnguyet/lunar ${pkg.version} (MIT), https://github.com/Nhat-Nguyet/nhatnguyet-lunar-ziwei-bazi-numerology`,
  `// Generated by examples/google-sheets/build.mjs; edit src/functions.js, not this file.`,
  `// Data: Nhat Nguyet (nhatnguyet.org)`,
  out.outputFiles[0].text.trimEnd(),
  "",
  readFileSync(new URL("src/functions.js", here), "utf8"),
].join("\n");

const target = new URL("Code.gs", here);
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(target, "utf8"); } catch {}
  if (current !== code) {
    console.error("Code.gs is out of date: run npm run build");
    process.exit(1);
  }
  console.log(`Code.gs is up to date (${code.length} bytes)`);
} else {
  writeFileSync(target, code);
  console.log(`wrote Code.gs (${code.length} bytes)`);
}
